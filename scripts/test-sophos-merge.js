const assert = require('node:assert/strict');
const {mergeReservations} = require('../sophos-sync');
const vlans = [{id:1,subnet:'192.168.1.0',cidr:24}];
const match = ip => ip.startsWith('192.168.1.');
const record = {ip:'192.168.1.5',mac:'aa:bb:cc:dd:ee:ff',host:'PC',interface:'Port1',dhcpServer:'LAN'};
const snapshot = {serverCount:1,fetchedAt:new Date().toISOString(),records:[record]};
const initial = mergeReservations(snapshot,[],vlans,match);
assert.equal(initial.imported,1);
assert.equal(initial.entries[0].status,'reserved');
assert.deepEqual(mergeReservations(snapshot,initial.entries,vlans,match).entries,initial.entries);
const manual = {id:'manual',ip:record.ip,host:'Keep me'};
const conflict = mergeReservations(snapshot,[manual],vlans,match);
assert.equal(conflict.conflicts.length,1);
assert.deepEqual(conflict.entries,[manual]);
const removed = mergeReservations({...snapshot,records:[{...record,ip:'192.168.1.6'}]},initial.entries,vlans,match);
assert.equal(removed.missing,1);
assert.equal(removed.entries.find(e=>e.ip===record.ip).sourceState,'missing');
assert.throws(()=>mergeReservations({...snapshot,records:[]},initial.entries,vlans,match),/Empty/);
assert.throws(()=>mergeReservations({...snapshot,records:[record,record]},[],vlans,match),/Duplicate/);
assert.throws(()=>mergeReservations({...snapshot,records:[{...record,ip:'invalid'}]},[],vlans,match),/Invalid/);
console.log('Import, repeat sync, conflict preservation, removal retention and invalid-response checks passed.');
